using Microsoft.AspNetCore.Localization;
using System.Globalization;


public static class LanguageHelper
{
    public static CultureInfo[] SupportedCultures = new[]
    {
        new CultureInfo("zh-Hans"), //This will be the default application culture
        new CultureInfo("en"),
        new CultureInfo("de"),
        new CultureInfo("zh-Hant"),
    };
    public static void SetDefaultCulture(this IServiceCollection services)
    {
        services.Configure<RequestLocalizationOptions>(options =>
        {
            options.DefaultRequestCulture = new RequestCulture(SupportedCultures.First());
            options.SupportedCultures = SupportedCultures;
            options.SupportedUICultures = SupportedCultures;
            options.RequestCultureProviders.Add(new CookieRequestCultureProvider());
        });
    }
    public static void SetRequestLocalization(this WebApplication app)
    {
        var _supportedCultures = SupportedCultures.Select(i=>i.IetfLanguageTag).ToArray();
        var localizationOptions = new RequestLocalizationOptions().SetDefaultCulture(_supportedCultures[0])
            .AddSupportedCultures(_supportedCultures)
            .AddSupportedUICultures(_supportedCultures);
        localizationOptions.RequestCultureProviders = new List<IRequestCultureProvider>
        {
            new CookieRequestCultureProvider()
        };
        app.UseRequestLocalization(localizationOptions);
    }
    public static void SetLanguage(string languagecode, string? redirectUri, HttpRequest request)
        {
            //string? languagecode = request.Query.FirstOrDefault(i => i.Key.Equals("langcode", StringComparison.OrdinalIgnoreCase)).Value;
            //string? redirectUri = request.Query.FirstOrDefault(i => i.Key.Equals("redirectUri", StringComparison.OrdinalIgnoreCase)).Value;
            if (redirectUri == null) redirectUri = "/";
            if (languagecode != null)
            {
                request.HttpContext.Response.Cookies.Append(
                Microsoft.AspNetCore.Localization.CookieRequestCultureProvider.DefaultCookieName,
                Microsoft.AspNetCore.Localization.CookieRequestCultureProvider.MakeCookieValue(new Microsoft.AspNetCore.Localization.RequestCulture(languagecode, languagecode)),
                    new CookieOptions
                    {
                        Expires = DateTimeOffset.UtcNow.AddYears(1),
                        IsEssential = true,
                        HttpOnly = false,
                        SameSite = SameSiteMode.None,
                        Secure = true
                    }
                );
            }

            request.HttpContext.Response.Redirect(redirectUri);
        }
