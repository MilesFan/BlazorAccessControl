    /// <summary>
    /// A workaround to get language native name.
    /// https://github.com/dotnet/runtime/issues/44739
    /// </summary>
    /// <param name="LanguageTag">
    /// RFC 4646 languagecode2 + country/regioncode(optional), for example: en-US, zh-CN, or simply en, zh
    /// </param>
    /// <returns>The display name of specified language code in native characters.</returns>
    public static string GetNativeName(string LanguageTag)
    {
        if (string.IsNullOrWhiteSpace(LanguageTag)) return "Unknown Language";
        if (!LanguageNativeNames.TryGetValue(LanguageTag, out var nativeName)) return "Unknown Language";
        return nativeName;
    }
